"""METINAR-013 — Venomous Spider (Trujący Pająk): original procedural model + rig, authored for MetinAR.

Run inside Blender 4.2 LTS (headless):  blender -b --python spider_model.py -- <stage> [out_dir]
This module only builds geometry, skin weights and the armature; see spider_build.py for the full pipeline.

Coordinates: Blender metres, Z up, the spider faces -Y (Blender Front view). FBX export with
forward -Z / up Y + Unity "Bake Axis Conversion" turns that into Unity +Z forward, +Y up.
Everything here is generated by this script: no external meshes, textures, scans or AI output.
"""
import math

import bmesh
import bpy
from mathutils import Matrix, Vector

# Region ids (stored in the "Data" colour attribute, R = id / 10).
REG_BODY, REG_HEAD, REG_ABDOMEN, REG_LEG, REG_EYE, REG_FANG, REG_SPIKE = 1, 2, 3, 4, 5, 6, 7

SIDES = (("L", 1.0), ("R", -1.0))  # facing -Y, the spider's left side is +X
# Per leg pair (01 = front ... 04 = back): hip Y, foot Y (Blender Y, -Y = front), foot X, knee height.
LEG_LAYOUT = [
    (-0.235, -0.640, 0.540, 0.56),
    (-0.165, -0.300, 0.640, 0.54),
    (-0.085, 0.060, 0.640, 0.52),
    (-0.010, 0.430, 0.560, 0.54),
]
HIP_X, HIP_Z = 0.125, 0.300
FOOT_Z = 0.012

CEPH_C, CEPH_R = Vector((0.0, -0.140, 0.300)), Vector((0.170, 0.185, 0.125))
HEAD_C, HEAD_R = Vector((0.0, -0.300, 0.305)), Vector((0.105, 0.085, 0.085))
ABD_C, ABD_R = Vector((0.0, 0.250, 0.365)), Vector((0.265, 0.330, 0.215))


class Builder:
    """Accumulates geometry with per-vertex region / aux data and bone weights."""

    def __init__(self):
        self.bm = bmesh.new()
        self.vdata = []  # (region, auxG, auxB)
        self.weights = []  # dict bone -> weight

    def vert(self, co, region, weights, aux_g=0.0, aux_b=0.0):
        v = self.bm.verts.new(co)
        self.vdata.append((region, aux_g, aux_b))
        self.weights.append(weights)
        return v

    def face(self, verts):
        return self.bm.faces.new(verts)


def leg_points(i, sx):
    hip_y, foot_y, foot_x, knee_z = LEG_LAYOUT[i]
    hip = Vector((HIP_X * sx, hip_y, HIP_Z))
    foot = Vector((foot_x * sx, foot_y, FOOT_Z))
    knee_xy = hip.lerp(foot, 0.52)
    knee = Vector((knee_xy.x, knee_xy.y, knee_z))
    coxa_end = hip.lerp(knee, 0.22)
    coxa_end.z -= 0.01
    return hip, coxa_end, knee, foot


def leg_bone_names(i, side):
    base = "B_Leg%s_%02d" % (side, i + 1)
    return base + "_Coxa", base + "_Upper", base + "_Lower"


def frame_for(direction, prev_normal=None):
    d = direction.normalized()
    ref = prev_normal if prev_normal is not None else Vector((0, 0, 1))
    n = ref - d * ref.dot(d)
    if n.length < 1e-4:
        n = Vector((1, 0, 0)) - d * d.x
    n.normalize()
    b = d.cross(n).normalized()
    return n, b


def add_ellipsoid(builder, center, radii, u_seg, v_seg, region, weight_fn, shape_fn=None, aux_fn=None):
    rings = []
    top = None
    bottom = None
    for j in range(1, v_seg):
        theta = math.pi * j / v_seg
        ring = []
        for k in range(u_seg):
            phi = 2 * math.pi * k / u_seg
            local = Vector((math.sin(theta) * math.cos(phi), math.sin(theta) * math.sin(phi), math.cos(theta)))
            if shape_fn:
                local = shape_fn(local)
            co = Vector((center.x + local.x * radii.x, center.y + local.y * radii.y, center.z + local.z * radii.z))
            aux = aux_fn(local) if aux_fn else (0.0, 0.0)
            ring.append(builder.vert(co, region, weight_fn(co), aux[0], aux[1]))
        rings.append(ring)
    top_local = shape_fn(Vector((0, 0, 1))) if shape_fn else Vector((0, 0, 1))
    bot_local = shape_fn(Vector((0, 0, -1))) if shape_fn else Vector((0, 0, -1))
    for local, which in ((top_local, "top"), (bot_local, "bottom")):
        co = Vector((center.x + local.x * radii.x, center.y + local.y * radii.y, center.z + local.z * radii.z))
        aux = aux_fn(local) if aux_fn else (0.0, 0.0)
        v = builder.vert(co, region, weight_fn(co), aux[0], aux[1])
        if which == "top":
            top = v
        else:
            bottom = v
    for j in range(len(rings) - 1):
        for k in range(u_seg):
            k2 = (k + 1) % u_seg
            builder.face([rings[j][k], rings[j][k2], rings[j + 1][k2], rings[j + 1][k]])
    for k in range(u_seg):
        k2 = (k + 1) % u_seg
        builder.face([top, rings[0][k2], rings[0][k]])
        builder.face([bottom, rings[-1][k], rings[-1][k2]])


def add_tube(builder, points, radii, sides, rings_per_seg, region, weight_fn, aux_fn, tip=None, cap_start=True):
    """Tube through a polyline; rings_per_seg[i] rings on segment i (joint rings shared)."""
    ring_list = []
    prev_n = None
    seg_count = len(points) - 1
    for s in range(seg_count):
        a, b = points[s], points[s + 1]
        n_r = rings_per_seg[s]
        for r in range(n_r + (1 if s == seg_count - 1 else 0)):
            t = r / n_r
            p = a.lerp(b, t)
            if s > 0 and r == 0:
                d = ((b - a).normalized() + (points[s] - points[s - 1]).normalized())
            else:
                d = b - a
            n, bn = frame_for(d, prev_n)
            prev_n = n
            rad = radii[s] + (radii[s + 1] - radii[s]) * t
            ring = []
            for k in range(sides):
                ang = 2 * math.pi * k / sides
                co = p + (n * math.cos(ang) + bn * math.sin(ang)) * rad
                g, bb = aux_fn(s, t)
                ring.append(builder.vert(co, region, weight_fn(s, t), g, bb))
            ring_list.append(ring)
    for j in range(len(ring_list) - 1):
        for k in range(sides):
            k2 = (k + 1) % sides
            builder.face([ring_list[j][k], ring_list[j][k2], ring_list[j + 1][k2], ring_list[j + 1][k]])
    if cap_start:
        c = builder.vert(points[0], region, weight_fn(0, 0.0), *aux_fn(0, 0.0))
        for k in range(sides):
            builder.face([c, ring_list[0][(k + 1) % sides], ring_list[0][k]])
    end = tip if tip is not None else points[-1]
    e = builder.vert(end, region, weight_fn(seg_count - 1, 1.0), *aux_fn(seg_count - 1, 1.0))
    for k in range(sides):
        builder.face([ring_list[-1][k], ring_list[-1][(k + 1) % sides], e])


def smooth01(x):
    x = max(0.0, min(1.0, x))
    return x * x * (3 - 2 * x)


def build_mesh(name="SK_Mob_VenomousSpider_LOD0"):
    bld = Builder()

    # Cephalothorax: weight to B_Body, blending into B_Abdomen at the waist and B_Head at the front.
    def ceph_w(co):
        front = smooth01((-co.y - 0.24) / 0.08)
        return {"B_Body": 1.0 - 0.5 * front, "B_Head": 0.5 * front}

    def ceph_shape(l):
        # flatter underside, slight dorsal hump
        z = l.z * (0.75 if l.z < 0 else 1.0) + 0.12 * max(0.0, 1 - abs(l.y)) * max(0.0, l.z)
        return Vector((l.x * (1.0 - 0.15 * max(0.0, -l.y)), l.y, z))

    add_ellipsoid(bld, CEPH_C, CEPH_R, 22, 12, REG_BODY, ceph_w, ceph_shape)

    # Head with brow ridge.
    def head_shape(l):
        z = l.z + 0.18 * max(0.0, -l.y) * max(0.0, l.z)
        return Vector((l.x, l.y * (1.0 + 0.1 * max(0.0, -l.y)), z))

    add_ellipsoid(bld, HEAD_C, HEAD_R, 16, 10, REG_HEAD, lambda co: {"B_Head": 1.0}, head_shape)

    # Abdomen: tapered towards the spinnerets, aux G/B = normalized local coords for the painter.
    def abd_w(co):
        waist = smooth01((0.02 - co.y) / 0.10)
        return {"B_Abdomen": 1.0 - 0.5 * waist, "B_Body": 0.5 * waist}

    def abd_shape(l):
        # l.y in [-1,1] front→back; taper the back and lift the front shoulder.
        taper = 1.0 - 0.32 * max(0.0, l.y) ** 2
        z = l.z * (0.85 if l.z < 0 else 1.0) * taper + 0.10 * max(0.0, -l.y) * max(0.0, l.z)
        return Vector((l.x * taper, l.y * (1.0 + 0.06 * max(0.0, l.y)), z))

    add_ellipsoid(bld, ABD_C, ABD_R, 32, 18, REG_ABDOMEN, abd_w, abd_shape)

    # Dorsal spikes on the abdomen (threatening silhouette).
    for idx, (u, h) in enumerate(((-0.55, 0.06), (-0.25, 0.075), (0.05, 0.07), (0.35, 0.055))):
        for sx in ((0.0,) if idx == 0 else (-1.0, 1.0)):
            lx = sx * 0.28
            local = abd_shape(Vector((lx, u, math.sqrt(max(0.0, 1 - lx * lx - u * u)))))
            base = Vector((ABD_C.x + local.x * ABD_R.x, ABD_C.y + local.y * ABD_R.y, ABD_C.z + local.z * ABD_R.z - 0.01))
            tip = base + Vector((sx * 0.015, 0.03, h))
            add_tube(bld, [base, base.lerp(tip, 0.5)], [0.022, 0.012], 6, [1], REG_SPIKE,
                     lambda s, t: {"B_Abdomen": 1.0}, lambda s, t: (t * 0.5, 0.0), tip=tip, cap_start=False)

    # Eyes: two large, four small, on the head front.
    eye_specs = [(0.038, 0.032, -0.355, 0.355), (0.026, 0.078, -0.335, 0.345), (0.020, 0.058, -0.372, 0.318)]
    for r, x, y, z in eye_specs:
        for sx in (-1.0, 1.0):
            add_ellipsoid(bld, Vector((x * sx, y, z)), Vector((r, r, r)), 8, 6, REG_EYE, lambda co: {"B_Head": 1.0})

    # Fangs (chelicerae): curved, tapered, pale; aux G = 0 base → 1 tip.
    for side, sx in SIDES:
        bone = "B_Fang_" + side
        p0 = Vector((0.042 * sx, -0.360, 0.265))
        p1 = Vector((0.048 * sx, -0.405, 0.205))
        p2 = Vector((0.036 * sx, -0.420, 0.145))
        tip = Vector((0.020 * sx, -0.398, 0.100))
        add_tube(bld, [p0, p1, p2], [0.030, 0.024, 0.015], 7, [3, 3], REG_FANG,
                 lambda s, t, b=bone: {b: 1.0}, lambda s, t: ((s + t) / 2.0, 0.0), tip=tip)

    # Legs: coxa / upper (femur) / lower (tibia+tarsus); aux G = position along the leg (0 hip → 1 tip),
    # aux B = closeness to a joint (1 at a joint) for painted joint bands.
    for i in range(4):
        for side, sx in SIDES:
            hip, coxa_end, knee, foot = leg_points(i, sx)
            names = leg_bone_names(i, side)
            # extra point at the "ankle" for a claw-like bend
            ankle = knee.lerp(foot, 0.78)
            ankle += Vector((0.0, 0.0, 0.035))
            pts = [hip, coxa_end, knee, ankle, foot]
            radii = [0.046, 0.042, 0.034, 0.020, 0.010]
            rings = [2, 5, 5, 2]
            seg_bone = [0, 1, 2, 2]

            def w_fn(s, t, names=names, seg_bone=seg_bone):
                b = seg_bone[s]
                if s in (1, 2) and t < 0.18:
                    blend = 0.5 * (1.0 - t / 0.18)
                    return {names[b]: 1.0 - blend, names[b - 1]: blend}
                return {names[b]: 1.0}

            lengths = [(pts[k + 1] - pts[k]).length for k in range(4)]
            total = sum(lengths)
            starts = [sum(lengths[:k]) for k in range(4)]

            def a_fn(s, t, lengths=lengths, total=total, starts=starts):
                along = (starts[s] + lengths[s] * t) / total
                joint_d = min(abs(t), abs(1 - t)) * lengths[s]
                near = 1.0 - min(1.0, joint_d / 0.035) if s in (0, 1, 2) else 0.0
                return along, near

            tip = foot + (foot - ankle).normalized() * 0.015
            tip.z = 0.0
            add_tube(bld, pts, radii, 10, rings, REG_LEG, w_fn, a_fn, tip=tip)
            # one spike on the upper segment
            sp_base = coxa_end.lerp(knee, 0.55) + Vector((0, 0, 0.03))
            sp_tip = sp_base + Vector((0.02 * sx, 0.01, 0.07))
            add_tube(bld, [sp_base, sp_base.lerp(sp_tip, 0.45)], [0.016, 0.009], 5, [1], REG_SPIKE,
                     lambda s, t, n=names[1]: {n: 1.0}, lambda s, t: (t * 0.5, 0.0), tip=sp_tip, cap_start=False)

    bm = bld.bm
    bm.verts.index_update()
    # consistent outward winding for every part (ellipsoids are generated inside-out)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    bmesh.ops.triangulate(bm, faces=bm.faces[:], quad_method="BEAUTY", ngon_method="BEAUTY")
    for f in bm.faces:
        f.smooth = True
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()

    attr = me.color_attributes.new("Data", "FLOAT_COLOR", "POINT")
    for i, (reg, g, b) in enumerate(bld.vdata):
        attr.data[i].color = (reg / 10.0, g, b, 1.0)
    obj = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(obj)
    for i, w in enumerate(bld.weights):
        for bone, value in w.items():
            if value <= 0.0:
                continue
            vg = obj.vertex_groups.get(bone) or obj.vertex_groups.new(name=bone)
            vg.add([i], value, "REPLACE")
    return obj


DEFORM_BONES = []


def build_armature(name="Rig"):
    arm = bpy.data.armatures.new(name)
    obj = bpy.data.objects.new(name, arm)
    bpy.context.scene.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.mode_set(mode="EDIT")
    eb = arm.edit_bones

    def bone(n, head, tail, parent=None, deform=True, connect=False):
        b = eb.new(n)
        b.head, b.tail = Vector(head), Vector(tail)
        b.roll = 0.0
        if parent:
            b.parent = eb[parent]
            b.use_connect = connect
        b.use_deform = deform
        return b

    bone("B_Root", (0, 0, 0), (0, 0, 0.10))
    bone("B_Body", (0, -0.10, 0.30), (0, -0.10, 0.42), "B_Root")
    bone("B_Abdomen", (0, 0.02, 0.34), (0, 0.55, 0.40), "B_Body")
    bone("B_Head", (0, -0.24, 0.30), (0, -0.37, 0.31), "B_Body")
    for side, sx in SIDES:
        bone("B_Fang_" + side, (0.042 * sx, -0.360, 0.265), (0.030 * sx, -0.415, 0.120), "B_Head")
    for i in range(4):
        for side, sx in SIDES:
            hip, coxa_end, knee, foot = leg_points(i, sx)
            c, u, l = leg_bone_names(i, side)
            bone(c, hip, coxa_end, "B_Body")
            bone(u, coxa_end, knee, c, connect=True)
            bone(l, knee, foot, u, connect=True)
            # Blender-only controls (not exported: use_deform=False)
            bone("IK_Foot_%s%02d" % (side, i + 1), foot, foot + Vector((0, 0, 0.06)), "B_Root", deform=False)
            # pole in the leg's bend plane, beyond the knee (stable knee direction)
            pole = knee + (knee - coxa_end.lerp(foot, 0.5)).normalized() * 0.4
            bone("IK_Pole_%s%02d" % (side, i + 1), pole, pole + Vector((0, 0, 0.05)), "B_Body", deform=False)
    bpy.ops.object.mode_set(mode="OBJECT")
    DEFORM_BONES[:] = [b.name for b in arm.bones if b.use_deform]

    for i in range(4):
        for side, _ in SIDES:
            _, _, lower = leg_bone_names(i, side)
            con = obj.pose.bones[lower].constraints.new("IK")
            con.target = obj
            con.subtarget = "IK_Foot_%s%02d" % (side, i + 1)
            con.pole_target = obj
            con.pole_subtarget = "IK_Pole_%s%02d" % (side, i + 1)
            con.chain_count = 2
            con.use_tail = True
            con.use_stretch = False
    calibrate_poles(obj)
    return obj


def calibrate_poles(rig):
    """Pick each IK pole angle so the solved rest pose equals the modelled rest pose (no knee twist)."""
    for pb in rig.pose.bones:
        for con in pb.constraints:
            if con.type != "IK":
                continue
            upper = pb.parent
            rest_knee = rig.data.bones[upper.name].tail_local.copy()
            rest_foot = rig.data.bones[pb.name].tail_local.copy()

            def err(angle):
                con.pole_angle = angle
                bpy.context.view_layer.update()
                return (upper.tail - rest_knee).length + (pb.tail - rest_foot).length

            best = min((err(math.radians(a)), a) for a in range(-180, 180, 2))[1]
            fine = min((err(math.radians(best + d * 0.25)), best + d * 0.25) for d in range(-16, 17))[1]
            con.pole_angle = math.radians(fine)
            bpy.context.view_layer.update()
            residual = (upper.tail - rest_knee).length + (pb.tail - rest_foot).length
            if residual > 0.003:
                raise RuntimeError("IK pole calibration failed for %s (residual %.4f m)" % (pb.name, residual))


def bind(mesh_obj, rig):
    mesh_obj.parent = rig
    mod = mesh_obj.modifiers.new("Armature", "ARMATURE")
    mod.object = rig


def triangle_count(obj):
    return sum(len(p.vertices) - 2 for p in obj.data.polygons)
